#!/usr/bin/env python3
"""Deterministic OpenAI-compatible mock router for local orchestrator tests.

This is a test double, not a model. It reads ``mock_cases.json`` (generated by
``build_mock_cases.py``) and returns case-specific codes so a live comparison
exercises the real Docker/Redis/Postgres/evaluator paths without a paid router.

Scripted behaviors, clearly labeled as such:

* C05 - if history is visible, the coder recaptures the historical COPD HCC and
  the H3 verifier removes it.
* C06 - only a harness that receives history can return ``Z94.0``; without
  history the coder returns the less-specific ``Z94.9``.

Do not use these outputs to rank harness quality.

Usage:
    python mock_llm.py [port] [log_path]
"""

from __future__ import annotations

import json
import os
import sys
import tempfile
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

HERE = Path(__file__).resolve().parent
CASES_PATH = Path(os.getenv("MOCK_CASES", str(HERE / "mock_cases.json")))
LOG = os.getenv(
    "MOCK_LOG", str(Path(tempfile.gettempdir()) / "mock_requests.jsonl")
)

CASES = json.loads(CASES_PATH.read_text(encoding="utf-8"))["cases"]
BY_ID = {case["case_id"]: case for case in CASES}

PLANNER_MARK = "You are the planner"
CODER_MARK = "You are the coder"
VERIFIER_MARK = "You are the verifier"
FEEDBACK_MARK = "VERIFIER FEEDBACK"


def normalize(value: object) -> str:
    return " ".join(str(value or "").split()).casefold()


def find_case(text: str) -> dict | None:
    normalized = normalize(text)
    matches = [
        case
        for case in CASES
        if normalize(case["marker"]) and normalize(case["marker"]) in normalized
    ]
    if not matches:
        return None
    # Prefer the most specific marker when notes share a prefix.
    return max(matches, key=lambda case: len(case["marker"]))


def history_present(text: str) -> bool:
    if "HISTORY FIXTURE" not in text:
        return False
    tail = text.split("HISTORY FIXTURE", 1)[1].lstrip()
    return not (tail.startswith("{}") or tail.startswith("null"))


def history_has_organ(case: dict, text: str) -> bool:
    marker = case.get("history_marker") or ""
    return bool(marker) and normalize(marker) in normalize(text)


def gold_codes(case: dict, *, history_visible: bool, history_text: str) -> list[dict]:
    if (
        case["case_id"] == "C06"
        and case.get("without_history_code")
        and not history_has_organ(case, history_text)
    ):
        snippet = case["codes"][0]["snippet"]
        return [
            {
                "code": case["without_history_code"],
                "system": "ICD-10-CM",
                "snippet": snippet,
                "rationale": (
                    "The note documents transplant follow-up but does not "
                    "specify the organ without history."
                ),
            }
        ]
    return [
        {
            "code": item["code"],
            "system": item["system"],
            "snippet": item["snippet"],
            "rationale": item["rationale"],
        }
        for item in case["codes"]
    ]


def coder_codes(
    case: dict, *, history_text: str, revised: bool
) -> list[dict]:
    codes = gold_codes(
        case, history_visible=history_present(history_text), history_text=history_text
    )
    trap = case.get("trap_code")
    if trap and history_present(history_text) and not revised:
        codes = codes + [
            {
                "code": trap,
                "system": "ICD-10-CM",
                "snippet": case.get("trap_snippet") or case["codes"][0]["snippet"],
                "rationale": (
                    "History lists this prior HCC; the coder recaptures it "
                    "without checking current documentation."
                ),
            }
        ]
    return codes


def plan_for(case: dict, *, history_text: str) -> dict:
    codes = gold_codes(
        case, history_visible=history_present(history_text), history_text=history_text
    )
    gold = {item["code"] for item in case["codes"]}
    return {
        "conditions": [
            {
                "condition": item["label"],
                "status": "active",
                "evidence": item["snippet"],
                "history_support": (
                    "History confirms the condition."
                    if history_present(history_text)
                    else ""
                ),
            }
            for item in case["codes"]
        ],
        "candidate_codes": [
            {
                "code": item["code"],
                "system": item["system"],
                "why": "Documented in the current encounter note.",
            }
            for item in codes
        ],
        "do_not_code": [
            {
                "code": code,
                "reason": (
                    "Historical HCC, prior claim, or less-specific code that is "
                    "not supported by the current note."
                ),
            }
            for code in case.get("forbidden") or []
            if code not in gold
        ],
    }


def extract_draft(text: str) -> str:
    """Return only the coder draft from a verifier prompt.

    The verifier prompt also contains the planner findings and the history
    fixture, both of which can mention the trap code. Inspecting the whole
    prompt would reject a corrected revision.
    """
    if "CODER DRAFT" not in text:
        return text
    tail = text.split("CODER DRAFT", 1)[1]
    for marker in ("PRIOR VERIFIER FEEDBACK", "Produce the verifier JSON now"):
        if marker in tail:
            tail = tail.split(marker, 1)[0]
    return tail


def parse_codes(text: str) -> list[dict] | None:
    try:
        payload = json.loads(text.strip())
    except ValueError:
        return None
    if not isinstance(payload, dict):
        return None
    codes = payload.get("codes")
    if not isinstance(codes, list):
        return None
    return [item for item in codes if isinstance(item, dict)]


def verifier_payload(
    case: dict, *, history_text: str, draft: str, revised: bool
) -> dict:
    draft_codes = parse_codes(draft) or []
    trap = case.get("trap_code")
    if (
        trap
        and history_present(history_text)
        and any(str(item.get("code")) == trap for item in draft_codes)
    ):
        return {
            "approved": False,
            "issues": [
                {
                    "code": trap,
                    "problem": (
                        "Historical HCC is not documented in the current note; "
                        "do not recapture it."
                    ),
                    "action": "remove",
                }
            ],
            "codes": gold_codes(
                case,
                history_visible=True,
                history_text=history_text,
            ),
        }
    return {
        "approved": True,
        "issues": [],
        "codes": draft_codes
        or gold_codes(
            case,
            history_visible=history_present(history_text),
            history_text=history_text,
        ),
    }


def response_for(parsed: dict) -> str:
    messages = parsed.get("messages") or []
    system = str(messages[0].get("content", "")) if messages else ""
    user = "\n".join(str(message.get("content", "")) for message in messages[1:])
    case = find_case(user) or find_case(system) or BY_ID.get("C01") or CASES[0]

    if VERIFIER_MARK in system:
        payload = verifier_payload(
            case,
            history_text=user,
            draft=extract_draft(user),
            revised=FEEDBACK_MARK in user,
        )
    elif PLANNER_MARK in system:
        payload = plan_for(case, history_text=user)
    else:
        revised = FEEDBACK_MARK in user
        payload = {
            "codes": coder_codes(
                case, history_text=user, revised=revised
            )
        }
    return json.dumps(payload)


def log_request(path: str, parsed: dict) -> None:
    """Best-effort request log. Never fail a request because logging failed."""
    if not LOG:
        return
    try:
        log_path = Path(LOG)
        log_path.parent.mkdir(parents=True, exist_ok=True)
        with log_path.open("a", encoding="utf-8") as handle:
            handle.write(json.dumps({"path": path, "body": parsed}) + "\n")
    except OSError:
        pass


class Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def _json(self, payload: object, status: int = 200) -> None:
        data = json.dumps(payload).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        self.wfile.write(data)

    def do_GET(self) -> None:
        if self.path.rstrip("/") in {"/v1/models", "/models"}:
            self._json(
                {
                    "object": "list",
                    "data": [
                        {
                            "id": "mock/clinical-coder",
                            "object": "model",
                            "owned_by": "mock",
                        }
                    ],
                }
            )
        elif self.path.rstrip("/") in {"/health", "/v1/health"}:
            self._json({"status": "ok", "mode": "deterministic-mock"})
        else:
            self._json({"error": "not found"}, 404)

    def do_POST(self) -> None:
        length = int(self.headers.get("content-length", "0"))
        body = self.rfile.read(length).decode("utf-8", "replace")
        try:
            parsed = json.loads(body)
        except ValueError:
            parsed = {"raw": body}
        log_request(self.path, parsed)

        if self.path.rstrip("/") == "/api/show":
            self._json({"error": "not found"}, 404)
            return

        content = response_for(parsed)
        model = parsed.get("model") or "mock/clinical-coder"
        if parsed.get("stream"):
            self.send_response(200)
            self.send_header("Content-Type", "text/event-stream")
            self.send_header("Cache-Control", "no-cache")
            self.send_header("Connection", "keep-alive")
            self.end_headers()
            self._sse(
                {
                    "id": "chatcmpl-mock",
                    "object": "chat.completion.chunk",
                    "created": int(time.time()),
                    "model": model,
                    "choices": [
                        {
                            "index": 0,
                            "delta": {"role": "assistant", "content": ""},
                            "finish_reason": None,
                        }
                    ],
                }
            )
            for start in range(0, len(content), 120):
                self._sse(
                    {
                        "id": "chatcmpl-mock",
                        "object": "chat.completion.chunk",
                        "created": int(time.time()),
                        "model": model,
                        "choices": [
                            {
                                "index": 0,
                                "delta": {"content": content[start : start + 120]},
                                "finish_reason": None,
                            }
                        ],
                    }
                )
            self._sse(
                {
                    "id": "chatcmpl-mock",
                    "object": "chat.completion.chunk",
                    "created": int(time.time()),
                    "model": model,
                    "choices": [
                        {"index": 0, "delta": {}, "finish_reason": "stop"}
                    ],
                    "usage": {
                        "prompt_tokens": 1200,
                        "completion_tokens": 180,
                        "total_tokens": 1380,
                    },
                }
            )
            self.wfile.write(b"data: [DONE]\n\n")
            self.wfile.flush()
            return

        self._json(
            {
                "id": "chatcmpl-mock",
                "object": "chat.completion",
                "created": int(time.time()),
                "model": model,
                "choices": [
                    {
                        "index": 0,
                        "message": {"role": "assistant", "content": content},
                        "finish_reason": "stop",
                    }
                ],
                "usage": {
                    "prompt_tokens": 1200,
                    "completion_tokens": 180,
                    "total_tokens": 1380,
                },
            }
        )

    def _sse(self, payload: object) -> None:
        self.wfile.write(b"data: " + json.dumps(payload).encode() + b"\n\n")
        self.wfile.flush()

    def log_message(self, *_args: object) -> None:
        pass


if __name__ == "__main__":
    port = int(sys.argv[1]) if len(sys.argv) > 1 else 4010
    if len(sys.argv) > 2:
        LOG = sys.argv[2]
    print(
        f"mock router on 0.0.0.0:{port} cases={len(CASES)} log={LOG}",
        flush=True,
    )
    ThreadingHTTPServer(("0.0.0.0", port), Handler).serve_forever()
